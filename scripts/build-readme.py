#!/usr/bin/env python3
"""Generate the gallery and attribution from the two small manifests."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = "https://raw.githubusercontent.com/lmctl-ai/lmgallery/main/"


def grid(cells, columns):
    rows = ["| " + " | ".join([""] * columns) + " |",
            "| " + " | ".join([":---:"] * columns) + " |"]
    for start in range(0, len(cells), columns):
        row = cells[start:start + columns]
        rows.append("| " + " | ".join(row + [""] * (columns - len(row))) + " |")
    return "\n".join(rows)


def documents():
    hosts = json.loads((ROOT / "catalog.json").read_text())
    examples = json.loads((ROOT / "showcases.json").read_text())
    cards = []
    table = ["| Host | Does | Release | Links |", "| :--- | :--- | :--- | :--- |"]
    for h in hosts:
        label = " · preview" if h["category"] == "preview" else ""
        repo_label = "repo" if h["repo_available"] else "planned repo"
        badge = f'[![latest release](https://img.shields.io/github/v/release/lmctl-ai/{h["name"]}?label=release&color=2563eb)]({h["releases"]})'
        cards.append(f'<a href="{h["repo"]}"><img src="{h["image"]}" width="280" '
                     f'alt="{h["caption"]}"></a><br>**{h["name"]}{label}** — {h["topic"]}'
                     f'<br>[{repo_label}]({h["repo"]}) · [releases]({h["releases"]})')
        table.append(f'| **[{h["name"]}]({h["repo"]})**{label} | {h["topic"]}: {h["caption"]} | {badge} | '
                     f'[{repo_label}]({h["repo"]}) · [examples]({h["repo"]}/tree/main/examples) · [releases]({h["releases"]}) |')
    preview = [h["name"] for h in hosts if h["category"] == "preview"]
    show_cards = []
    for e in examples:
        hosts_line = " → ".join(e["hosts"])
        show_cards.append(f'<a href="{e["file"]}"><img src="{e["image"]}" width="420" '
                          f'alt="{e["title"]}"></a><br>**{e["title"]}** · {hosts_line}'
                          f'<br><sub><code>lmctl {RAW}{e["file"]}</code></sub>')
    readme = f'''# lmgallery

{len(hosts)} scripting hosts, {len(examples)} runnable compositions: compute a result, then turn it into a picture.

{grid(cards, 3)}

Click a picture to explore its host. These are copied snapshots, credited in [image attribution](docs/ATTRIBUTION.md).
**Preview** marks first releases with smaller APIs: {", ".join(preview)}. Every host ships prebuilt binaries on its releases page; the badge shows the latest tag.

## Hosts at a glance

{chr(10).join(table)}

Each host is a separate program with its own `--dsl-schema`; one `.lms` program can bind several of them. The {len(examples)} compositions below do exactly that.

## Run a composition

Install the [lmctl runner](https://github.com/lmctl-ai/lmctl), then copy a caption command into an empty directory:

```sh
npm install -g @lmctl-ai/lmctl
lmctl {RAW}{examples[0]["file"]}
```

Each program installs its declared hosts on first use, executes every DSL block, and writes its picture to `images/` in the current directory. Data and bytecode are generated locally; no checkout or sibling files are needed. Host downloads require internet access; `GITHUB_TOKEN` can help with GitHub API download limits. Each program prints its output path and stops if computation or rendering fails.

{grid(show_cards, 2)}

The [example index](examples/README.md) describes the data passed between hosts. These are illustrative scientific and engineering models, with assumptions stated in the scripts.

## Reproduce and check

```sh
./test.sh                 # offline image integrity, attribution, manifests and local links
./test.sh --network       # also check published HTTP links; planned hosts are reported explicitly
./test.sh --run           # execute all {len(examples)} local scripts, each in a fresh directory
./test.sh --urls          # execute the {len(examples)} public autorun URLs in fresh directories
./examples/render-all.sh  # regenerate the {len(examples)} composition previews
```

The offline checks need only Python 3.10+. Executable checks additionally need lmctl/lmscript, released hosts (downloaded automatically), `ffmpeg` for the animated composition, and network access on a cold install. CI runs offline/link checks, verifies that every caption's raw URL exists on `main`, and executes all {len(examples)} scripts on Linux. Work directories and logs from executable checks are retained outside the checkout for inspection.

Host previews are exact copies recorded in `catalog.json`; composition previews are generated by the programs listed in `showcases.json`. To update documentation after changing either manifest, run `python3 scripts/build-readme.py`. See [maintenance notes](durable-memory/README.md).

## License

MIT for this gallery and its scripts; see [LICENSE](LICENSE). Copied artwork and its generating examples are credited in [ATTRIBUTION](docs/ATTRIBUTION.md), with the retained [upstream MIT notice](licenses/upstream-examples-MIT.txt). Host executables remain separate programs under their own licenses. In particular, lmblender's executable is GPL-3.0-or-later; this repository redistributes its rendered preview, not the renderer or its libraries.
'''
    attribution = ["# Image attribution", "", f"The {len(hosts)} host previews below are unmodified copies from sibling `docs/images/` directories. SHA-256 records the exact copied bytes. A working-tree preview is explicitly identified when the upstream asset was not yet committed at capture time; no unpublished source URL is claimed.", "", "The new `showcase-*` images are generated by this repository's MIT-licensed examples. No host binaries, third-party models, fonts or linked libraries are bundled.", ""]
    for h in hosts:
        source_image = f'[{h["source_image"]}]({h["source_image_url"]})' if h["source_image_url"] else f'`{h["source_image"]}` (publication pending)'
        source_script = f'[{h["source_script"]}]({h["source_script_url"]})' if h["source_script_url"] else f'`{h["source_script"]}` (publication pending)'
        attribution += [f'## {h["name"]}', "", f'- Copied file: [{h["image"]}](../{h["image"]})', f'- Origin: [{h["name"]}]({h["repo"]}), {source_image}', f'- Generating program: {source_script}', f'- Credit: {h["attribution"]}.', f'- Snapshot: {h["snapshot_note"]}.', f'- SHA-256: `{h["sha256"]}`', ""]
    index = ["# Cross-host compositions", "", "Every command runs from an empty directory and writes the listed image. Each computation is passed to a separate rendering host through generated data.", "", "| | |", "| :---: | :---: |"]
    for start in range(0, len(examples), 2):
        pair = examples[start:start + 2]
        index.append("| " + " | ".join(f'<a href="#{e["title"].lower().replace(" ", "-").replace(":", "").replace(",", "")}"><img src="../{e["image"]}" width="400" alt="{e["title"]}"></a><br>{e["title"]}' for e in pair) + (" | |" if len(pair) == 1 else " |"))
    index.append("")
    for e in examples:
        index += [f'## {e["title"]}', "", e["description"], "", f'Hosts: {" → ".join(e["hosts"])}. Output: `{e["output"]}`.', "", "```sh", f'lmctl {RAW}{e["file"]}', "```", ""]
    return {"README.md": readme, "docs/ATTRIBUTION.md": "\n".join(attribution), "examples/README.md": "\n".join(index)}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in documents().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"stale generated document: {name}; run scripts/build-readme.py")
        else:
            path.write_text(content)
